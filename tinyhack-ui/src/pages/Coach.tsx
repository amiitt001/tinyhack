import { useState } from 'react';
import { Send, Sparkles } from 'lucide-react';
import { Card, PageHead } from '../components/ui';
import { sendCoachMessage } from '../lib/api';
import { useApp } from '../lib/store';

type Message = { role: 'user' | 'assistant'; text: string };

function formatCoachText(text: string) {
  return text.split(/\n+/).map((line, index) => {
    const listMatch = line.match(/^\s*(\d+\.|[-*])\s+(.*)$/);
    const content = listMatch ? listMatch[2] : line;
    const parts = content.split(/(\*\*[^*]+\*\*)/g);
    return (
      <span className={`coach-line${listMatch ? ' coach-list-line' : ''}`} key={`${index}-${line}`}>
        {listMatch && <span className="coach-list-marker">{listMatch[1]}</span>}
        {parts.map((part, partIndex) =>
          part.startsWith('**') && part.endsWith('**') ? (
            <strong key={partIndex}>{part.slice(2, -2)}</strong>
          ) : (
            part
          ),
        )}
      </span>
    );
  });
}

export default function Coach() {
  const { state, toast } = useApp();
  const [input, setInput] = useState('');
  const [messages, setMessages] = useState<Message[]>([]);
  const [loading, setLoading] = useState(false);
  const profileSummary = [
    state.profile.role,
    state.profile.location,
    state.profile.skills,
    state.profile.experience,
    state.profile.projects,
    state.profile.interests,
  ].filter(Boolean).join('\n');

  async function send() {
    const message = input.trim();
    if (!message || loading) return;
    setInput('');
    setMessages((items) => [...items, { role: 'user', text: message }]);
    setLoading(true);
    try {
      const result = await sendCoachMessage(message, profileSummary);
      setMessages((items) => [...items, { role: 'assistant', text: result.response }]);
    } catch (error) {
      toast(error instanceof Error ? error.message : 'The AI career coach is unavailable.');
    } finally {
      setLoading(false);
    }
  }

  return (
    <>
      <PageHead eyebrow="GROUNDED IN YOUR JOURNEY" title="AI Career Coach" description="A thinking partner for your next chapter." />
      <Card>
        <div className="coach-banner">
          <span className="coach-symbol"><Sparkles size={20} /></span>
          <div>
            <h3>Your career, in context</h3>
            <p>{loading ? 'Thinking through your question…' : 'Ask a question and get advice grounded in your profile.'}</p>
          </div>
        </div>
        <div className="coach-messages">
          {messages.map((message, index) => (
            <div className={`coach-message ${message.role}`} key={`${message.role}-${index}`}>
              <strong>{message.role === 'user' ? 'You' : 'AI Career Coach'}</strong>
              <p>{message.role === 'assistant' ? formatCoachText(message.text) : message.text}</p>
            </div>
          ))}
        </div>
        <form className="coach-input" onSubmit={(event) => { event.preventDefault(); void send(); }}>
          <input value={input} onChange={(event) => setInput(event.target.value)} placeholder="Ask about your next chapter…" disabled={loading} />
          <button className="button" type="submit" disabled={loading || !input.trim()} aria-label="Send message"><Send size={16} /></button>
        </form>
        <p className="muted">Advice is generated by Gemini from the profile information you provide.</p>
      </Card>
    </>
  );
}
